#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# Calyx 系统镜像每周自动化构建与入库脚本
# ==============================================================================

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_DIR}"

echo "=========================================================="
echo "==> [$(date '+%Y-%m-%d %H:%M:%S')] 开始 Calyx 系统自动构建流水线"
echo "=========================================================="

# 1. 显式拉取 GitHub 远程代码仓库，确保包含最新的桌面配置与软件包列表
echo "==> [1/6] 从 GitHub 远程仓库同步最新代码与配置..."
task pull

# 2. 赋予所有必要脚本执行权限
echo "==> [2/6] 检查并更新脚本执行权限..."
task chmod

# 3. 从上游远程镜像仓库拉取最新的基础镜像
echo "==> [3/6] 从上游远程镜像仓库拉取最新基础系统镜像..."
task pull-base

# 4. 动态检测上游基础镜像内核，并按需构建驱动镜像
echo "==> [4/6] 动态检查基础镜像内核并准备驱动中间镜像..."
task ensure-kmods

# 5. 本地直接构建 NVIDIA 系统镜像
echo "==> [5/6] 本地直接构建 Calyx NVIDIA 系统镜像..."
task build-nvidia

# 6. 推送至私有仓并触发保留策略淘汰与垃圾回收
echo "==> [6/6] 推送系统镜像至本地私有仓并执行生命周期管理..."
task push-nvidia

# 7. 清理构建残留的临时悬挂镜像
echo "==> 清理构建过程产生的悬挂缓存镜像..."
podman image prune -f || true

echo "=========================================================="
echo "==> [$(date '+%Y-%m-%d %H:%M:%S')] Calyx 自动构建与推送流水线圆满完成！"
echo "=========================================================="
