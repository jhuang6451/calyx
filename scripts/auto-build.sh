#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# Calyx 系统镜像每周自动化构建与入库脚本
# ==============================================================================

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_DIR}"

echo "=========================================================="
echo "==> [$(date '+%Y-%m-%d %H:%M:%S')] 开始 Calyx 系统自动构建流水线"
echo "=========================================================="

# 1. 尝试同步远程 Git 仓库最新提交 (若无网络或有临时冲突则优雅回退)
echo "==> [1/5] 检查并同步 Git 仓库最新代码..."
if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  git pull --rebase origin master 2>/dev/null || echo "    [提示] git pull 跳过或无网络更新，使用本地工作区代码继续构建。"
fi

# 2. 赋予所有必要脚本执行权限
echo "==> [2/5] 检查脚本执行权限..."
task chmod

# 3. 动态检测上游基础镜像内核，并按需构建驱动镜像
echo "==> [3/5] 动态检查基础镜像内核并准备驱动中间镜像..."
task ensure-kmods

# 4. 构建 NVIDIA 系统镜像
echo "==> [4/5] 本地直接构建 Calyx NVIDIA 系统镜像..."
task build-nvidia

# 5. 推送至私有仓并触发保留策略淘汰与垃圾回收
echo "==> [5/5] 推送系统镜像至私有仓并执行生命周期管理..."
task push-nvidia

# 6. 清理构建残留的临时悬挂镜像
echo "==> 清理构建过程产生的悬挂缓存镜像..."
podman image prune -f || true

echo "=========================================================="
echo "==> [$(date '+%Y-%m-%d %H:%M:%S')] Calyx 自动构建与推送流水线圆满完成！"
echo "=========================================================="
